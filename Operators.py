#Arthematic Operators
a = 10
b = 5
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

##Comparison Operators
x = 10
y = 5
print("Equal:", x == y)
print("Not Equal:", x != y)
print("Greater than:", x > y)
print("Less than:", x < y)
print("Greater than or equal to:", x >= y)
print("Less than or equal to:", x <= y)

##Logical Operators
p = True
q = False
print("Logical AND:", p and q)
print("Logical OR:", p or q)
print("Logical NOT:", not p)    

##Assignment Operators
m = 10
m += 5
print("Assignment Operator (+=):", m)   

##Bitwise Operators
num1 = 10  # Binary: 1010
num2 = 4   # Binary: 0100
print("Bitwise AND:", num1 & num2)  # Binary: 0000
print("Bitwise OR:", num1 | num2)   # Binary: 1110
print("Bitwise XOR:", num1 ^ num2)  # Binary: 1110

#Exponential Operator
base = 2
exponent = 3
result = base ** exponent
print("Exponential Operator:", result)  # Output: 8

##Membership Operators
list1 = [1, 2, 3, 4, 5]
print("Membership Operator (in):", 3 in list1)
print("Membership Operator (not in):", 6 not in list1)  

